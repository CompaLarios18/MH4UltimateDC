// The model of the DSP without sound (N1-18). It does what Azahar's HLE DSP does to the state the
// application can see, one audio frame (kAudioFrameTicks) at a time, and nothing else:
//
//   - the pipes and the DSP state (Initialize, Shutdown, Wakeup, Sleep), including the structure
//     addresses the audio pipe returns and the interrupts the pipe writes raise;
//   - on every frame of a running DSP: the region the DSP reads (the higher frame counter, with the
//     wrap-around rule), every source's configuration (the dirty bits cleared as the DSP clears them),
//     its buffer queue, and the status written to the other region: enabled, the "buffer changed"
//     flag, the sync count, the position in the current buffer, the id of the current buffer and of
//     the last one;
//   - the mixers' configuration (the dirty bits cleared), the DSP status, and silence in the final
//     samples and in the intermediate mixes of an enabled aux bus.
//
// What it leaves out is the audio: no sample data is read or decoded, no resampling or filter runs,
// nothing is mixed and the output is silence. A source advances through its buffers by counting: a
// buffer of N samples holds N input samples (an ADPCM buffer, N rounded up to an even number), and
// every output sample consumes input exactly as Azahar's interpolation (AudioInterp, whatever the
// mode) does, from the rate multiplier in 24-bit fixed point, so the status fields come out the
// same. The model is single-threaded: it belongs to the scheduler thread (principle 6).
//
// Departures from Azahar, all deliberate (the DSP memory belongs to a game that must keep running):
//  - Where Azahar asserts (a register number other than 0, a pipe message of the wrong size, a pipe
//    that is not implemented, PCM8 or ADPCM in a partial embedded buffer update, a format value of 3,
//    a NaN rate multiplier), the model logs the error and goes on without the action.
//  - A frame stops dequeueing buffers after kMaxDequeuesPerFrame (Azahar loops for ever on a looping
//    buffer of length 0).
//  - A play position beyond the end of a buffer empties it (Azahar erases past the end).
//  - A buffer's address is valid when it lies in VRAM, DSP RAM, FCRAM (the size of the New 3DS's) or the
//    New 3DS's extra RAM, ends included (Azahar's GetPhysMemRegionInfo): the model has no mapping to
//    consult, because it reads no data.
//  - The binary pipe answers like Azahar's AAC decoder does when it fails to decode (a message with the
//    sample rate 48000, 2 channels and 1024 samples), since nothing is decoded.
