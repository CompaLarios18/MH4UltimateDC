#!/usr/bin/env python3
"""N0-23: service command census from tools/find_services.py's output.

Reads the TSV that find_services.py writes (columns: function, mode, service, header,
command, callers, site, handle, note; see its docstring and COLUMNS / request_rows /
svc_rows / write_tsv) and writes a Markdown document: per service, every command header
the game's code sends, its name (find_services' tables, or `?`) and how many distinct
request functions send it.

Groups:
  traced      the session handle was traced to a service name
  inferred    find_services could not trace the handle and guessed the service (its
              `service` column ends in '?'): neighbouring request functions or a header
              only one known service uses. These are marked and kept apart.
  untraced    no service at all (empty `service` column)

System-call rows (`service` = `svc`) are not IPC commands and are skipped. The output holds
service names, headers, command names and counts only: nothing else from the TSV (no
addresses, handle locations or notes) is copied.

usage: service_commands.py build/services.tsv -o docs/research/service-commands.md
       [--coverage docs/research/system-services.md]
With --coverage the tool also checks that every service of that file's session table
(first column of the table whose header has "Handle global") appears in the census, and
exits 1 listing the missing ones.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

REQUIRED = ("function", "service", "header", "command")
HEADER_RE = re.compile(r"^0x[0-9A-Fa-f]{1,8}$")


def read_rows(path: str | Path) -> list[dict[str, str]]:
    """Same reading rules as find_services.read_tsv: blank and '#' lines skipped, the
    first remaining line is the header."""
    rows: list[dict[str, str]] = []
    header: list[str] | None = None
    with open(path, encoding="utf-8", newline="") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if header is None:
                header = parts
                missing = [c for c in REQUIRED if c not in header]
                if missing:
                    raise ValueError(f"{path}: missing column(s) {', '.join(missing)}")
                continue
            rows.append(dict(zip(header, parts)))
    if header is None:
        raise ValueError(f"{path}: empty file")
    return rows


def _norm_header(h: str) -> int | None:
    return int(h, 16) if HEADER_RE.match(h) else None


def census(rows: list[dict[str, str]]) -> dict:
    """{'traced'|'inferred'|'untraced': {service: {header: (names, functions)}}, 'unknown_header': n}.

    functions is the set of distinct request functions that send the header."""
    groups: dict[str, dict[str, dict[int, tuple[set[str], set[str]]]]] = {
        "traced": defaultdict(dict), "inferred": defaultdict(dict), "untraced": defaultdict(dict)}
    unknown_header = 0
    for r in rows:
        svc = r.get("service", "")
        if svc == "svc":
            continue
        hdr = _norm_header(r.get("header", ""))
        if hdr is None:
            unknown_header += 1
            continue
        if not svc:
            group, name = "untraced", ""
        elif svc.endswith("?"):
            group, name = "inferred", svc[:-1]
        else:
            group, name = "traced", svc
        names, funcs = groups[group][name].setdefault(hdr, (set(), set()))
        names.add(r.get("command") or "?")
        funcs.add(r["function"])
    return {"groups": groups, "unknown_header": unknown_header}


def _name(names: set[str]) -> str:
    known = sorted(n for n in names if n != "?")
    return ", ".join(known) if known else "?"


def _table(commands: dict[int, tuple[set[str], set[str]]]) -> list[str]:
    out = ["| Header | Command | Request functions |", "|---|---|---|"]
    for hdr in sorted(commands):
        names, funcs = commands[hdr]
        out.append(f"| `0x{hdr:08x}` | {_name(names)} | {len(funcs)} |")
    return out


def render(rows: list[dict[str, str]]) -> str:
    c = census(rows)
    g = c["groups"]
    lines = [
        "# Service commands the game sends",
        "",
        "Generated by `tools/native/service_commands.py` from the output of `tools/find_services.py` "
        "(`build/services.tsv`). Do not edit by hand: regenerate it.",
        "",
        "Each row is a command header (`command id << 16 | normal words << 6 | translate words`), "
        "its name from `find_services.py`'s tables of public 3DS commands (`?` when the tables "
        "do not have it; a trailing `~` means the command id matches but the parameter counts differ "
        "from the table), and the number of distinct request functions in the game's code that send it. "
        "Headers, names and counts only: what a command does is for the service work packages to read "
        "from Azahar.",
        "",
    ]
    total_services = sum(len(g[k]) for k in g)
    total_cmds = sum(len(v) for k in g for v in g[k].values())
    lines += [f"{len(g['traced'])} traced services, {len(g['inferred'])} inferred, "
              f"{len(g['untraced'])} untraced group; {total_cmds} (service, header) pairs "
              f"in {total_services} groups.", ""]
    lines += ["## Traced services", "",
              "The session handle was traced back to a `GetServiceHandle` name (or a known session response).", ""]
    if not g["traced"]:
        lines += ["None.", ""]
    for svc in sorted(g["traced"]):
        lines += [f"### `{svc}`", ""] + _table(g["traced"][svc]) + [""]
    lines += ["## Inferred services", "",
              "**Not traced.** `find_services.py` could not follow the handle and inferred the service "
              "(neighbouring request functions, or a header that only one known service uses). "
              "Treat these as likely, not proven.", ""]
    if not g["inferred"]:
        lines += ["None.", ""]
    for svc in sorted(g["inferred"]):
        lines += [f"### `{svc}` (inferred)", ""] + _table(g["inferred"][svc]) + [""]
    lines += ["## Untraced requests", "",
              "Request functions with a constant header whose service could not be determined at all.", ""]
    if not g["untraced"]:
        lines += ["None.", ""]
    for svc in sorted(g["untraced"]):
        lines += _table(g["untraced"][svc]) + [""]
    if c["unknown_header"]:
        lines += [f"{c['unknown_header']} further request sites have a header that is not a constant "
                  "(not listed).", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def session_table_services(text: str) -> list[str]:
    """Services in the first column of the table whose header row has 'Handle global'."""
    out: list[str] = []
    in_table = False
    for line in text.splitlines():
        if not line.startswith("|"):
            in_table = False
            continue
        cells = [x.strip() for x in line.strip().strip("|").split("|")]
        if cells and cells[0] == "Service" and any("Handle global" in x for x in cells):
            in_table = True
            continue
        if not in_table or set(cells[0]) <= set("-: "):
            continue
        m = re.search(r"`([^`]+)`", cells[0])
        if m:
            out.append(m.group(1))
        elif cells[0].startswith("BOSS"):
            out.append("boss:U")                 # that row has no backticked name; the client is boss:U
        else:
            out.append(cells[0])
    return out


def missing_services(rows: list[dict[str, str]], session_text: str) -> list[str]:
    c = census(rows)["groups"]
    present = {s for k in c for s in c[k] if s}
    present |= {p for s in present for p in s.split("|")}
    return [s for s in session_table_services(session_text) if s not in present]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="service command census from find_services' TSV")
    ap.add_argument("tsv", help="build/services.tsv written by tools/find_services.py")
    ap.add_argument("-o", "--output", help="Markdown file to write (default stdout)")
    ap.add_argument("--coverage", metavar="MD", help="docs/research/system-services.md: check its session table")
    args = ap.parse_args(argv)
    try:
        rows = read_rows(args.tsv)
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    text = render(rows)
    if args.output:
        out = Path(args.output)
        out.parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    if args.coverage:
        try:
            missing = missing_services(rows, Path(args.coverage).read_text(encoding="utf-8"))
        except OSError as e:
            print(f"error: {e}", file=sys.stderr)
            return 2
        if missing:
            print("services of the session table missing from the census: " + ", ".join(missing),
                  file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
