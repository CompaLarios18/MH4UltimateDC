#!/usr/bin/env python3
"""Compile GLSL shaders into `uint32_t` SPIR-V arrays in one C++ include file (N2-25).

    spirv_inc.py IN_DIR OUT.inc

Each shader is compiled with `glslangValidator -V --target-env vulkan1.2` (apt: glslang-tools). IN_DIR/spirv_inc.txt
lists one array per line, `<array name> <file> [glslang options such as -DMODE=1]` (blank lines and `#` comments are
ignored; the lines of rhi-spike-evidence/shaders/build.sh take this form); a file may be listed several times with
different options. Without that file every shader in IN_DIR (`*.vert *.frag *.comp *.geom *.tesc *.tese`) gives one
array named after its file name, with each character that is not a letter or digit replaced by `_` (`tri.vert` ->
`tri_vert`).

The .inc files are committed: neither the build nor CI's native jobs need glslangValidator. Exit status: 0 ok,
1 a shader does not compile (the message names the file and carries glslang's output), 2 bad usage or tool missing.
"""
from __future__ import annotations

import argparse
import re
import shlex
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

SPIRV_MAGIC = 0x07230203
SHADER_SUFFIXES = (".vert", ".frag", ".comp", ".geom", ".tesc", ".tese")
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class ShaderError(Exception):
    pass


def array_name_for(file_name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", file_name)


def read_list(in_dir: Path) -> list[tuple[str, str, list[str]]]:
    """(array name, file, glslang options) for every array to build."""
    listing = in_dir / "spirv_inc.txt"
    entries: list[tuple[str, str, list[str]]] = []
    if listing.is_file():
        for number, raw in enumerate(listing.read_text(encoding="utf-8").splitlines(), start=1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = shlex.split(line)
            if len(parts) < 2:
                raise ShaderError(f"{listing}:{number}: expected '<array name> <file> [options]'")
            if not IDENTIFIER.match(parts[0]):
                raise ShaderError(f"{listing}:{number}: '{parts[0]}' is not an identifier")
            entries.append((parts[0], parts[1], parts[2:]))
    else:
        for path in sorted(in_dir.iterdir()):
            if path.suffix in SHADER_SUFFIXES:
                entries.append((array_name_for(path.name), path.name, []))
    names = [e[0] for e in entries]
    if len(set(names)) != len(names):
        raise ShaderError("an array name is used twice")
    if not entries:
        raise ShaderError(f"no shader in {in_dir}")
    return entries


def compile_shader(source: Path, options: list[str], glslang: str, workdir: Path) -> list[int]:
    out = workdir / "shader.spv"
    if out.exists():
        out.unlink()
    cmd = [glslang, "-V", "--target-env", "vulkan1.2", "-o", str(out), *options, str(source)]
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if proc.returncode != 0 or not out.is_file():
        raise ShaderError(f"{source.name}: glslangValidator failed:\n{proc.stdout.strip()}")
    data = out.read_bytes()
    if len(data) % 4 or len(data) < 20:
        raise ShaderError(f"{source.name}: not a SPIR-V module ({len(data)} bytes)")
    fmt = "<%dI" % (len(data) // 4)
    words = list(struct.unpack(fmt, data))
    if words[0] != SPIRV_MAGIC:
        words = list(struct.unpack(">%dI" % (len(data) // 4), data))
        if words[0] != SPIRV_MAGIC:
            raise ShaderError(f"{source.name}: bad SPIR-V magic 0x{words[0]:08x}")
    return words


def glslang_version(glslang: str) -> str:
    proc = subprocess.run([glslang, "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    first = proc.stdout.strip().splitlines()
    return first[0] if first else "glslangValidator"


def render(in_dir: Path, entries: list[tuple[str, str, list[str]]], glslang: str, workdir: Path) -> str:
    chunks = [
        f"// Generated by tools/native/spirv_inc.py from the shaders of its input folder with {glslang_version(glslang)}.\n"
        "// Do not edit; change the shaders and run the tool again. SPIR-V for Vulkan 1.2.\n"
        "#pragma once\n#include <cstdint>\n"
    ]
    for name, file_name, options in entries:
        source = in_dir / file_name
        if not source.is_file():
            raise ShaderError(f"{in_dir / 'spirv_inc.txt'}: {file_name} does not exist")
        words = compile_shader(source, options, glslang, workdir)
        suffix = f" {' '.join(options)}" if options else ""
        lines = []
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i : i + 8]) + ",")
        chunks.append(f"\n// {file_name}{suffix}\n[[maybe_unused]] static const uint32_t {name}[] = {{\n" + "\n".join(lines) + "\n};\n")
    return "".join(chunks)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="GLSL to SPIR-V arrays in a C++ include file.")
    parser.add_argument("in_dir", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args(argv)
    glslang = shutil.which("glslangValidator")
    if glslang is None:
        print("spirv_inc: glslangValidator is not on the PATH (apt install glslang-tools)", file=sys.stderr)
        return 2
    if not args.in_dir.is_dir():
        print(f"spirv_inc: {args.in_dir} is not a directory", file=sys.stderr)
        return 2
    try:
        entries = read_list(args.in_dir)
        with tempfile.TemporaryDirectory() as tmp:
            text = render(args.in_dir, entries, glslang, Path(tmp))
    except ShaderError as exc:
        print(f"spirv_inc: {exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"spirv_inc: wrote {len(entries)} arrays to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
